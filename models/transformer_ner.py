"""
Multilingual Transformer NER Pipeline for:
- mBERT (bert-base-multilingual-cased)
- XLM-RoBERTa (xlm-roberta-base)
- IndicBERT (ai4bharat/indic-bert)

Handles subword tokenization, BIO label alignment, fine-tuning, and inference.
"""

import os
import json
import torch
import torch.nn as nn
from typing import List, Dict, Any, Tuple
from transformers import AutoTokenizer, AutoModelForTokenClassification

MODELS_DIR = os.path.dirname(os.path.abspath(__file__))
SAVED_DIR = os.path.join(MODELS_DIR, "saved_models")
os.makedirs(SAVED_DIR, exist_ok=True)

SUPPORTED_TRANSFORMERS = {
    "mBERT": "bert-base-multilingual-cased",
    "XLM-R": "xlm-roberta-base",
    "IndicBERT": "ai4bharat/indic-bert"
}

ALL_LABELS = [
    "O",
    "B-SYMPTOM", "I-SYMPTOM",
    "B-RISK_INDICATOR", "I-RISK_INDICATOR",
    "B-SEVERITY", "I-SEVERITY",
    "B-DURATION", "I-DURATION",
    "B-BODY_PART", "I-BODY_PART"
]

LABEL2ID = {lbl: i for i, lbl in enumerate(ALL_LABELS)}
ID2LABEL = {i: lbl for lbl, i in LABEL2ID.items()}

class TransformerNER:
    def __init__(self, model_name_key: str = "mBERT", device: str = None):
        self.model_name_key = model_name_key
        self.model_name = SUPPORTED_TRANSFORMERS.get(model_name_key, "bert-base-multilingual-cased")
        self.device = device or ("cuda" if torch.cuda.is_available() else "cpu")
        self.tokenizer = None
        self.model = None
        self.label2id = LABEL2ID
        self.id2label = ID2LABEL

    def initialize_model(self):
        """Loads pre-trained tokenizer and model architecture."""
        try:
            print(f"Loading {self.model_name}...")
            self.tokenizer = AutoTokenizer.from_pretrained(self.model_name)
            self.model = AutoModelForTokenClassification.from_pretrained(
                self.model_name,
                num_labels=len(self.label2id),
                id2label=self.id2label,
                label2id=self.label2id
            ).to(self.device)
            return True
        except Exception as e:
            print(f"Notice: Offline/Local mode for {self.model_name}: {e}")
            return False

    def tokenize_and_align_labels(self, tokens: List[str], tags: List[str]):
        """Aligns subwords generated by WordPiece / SentencePiece with word-level BIO tags."""
        tokenized_inputs = self.tokenizer(
            tokens,
            is_split_into_words=True,
            truncation=True,
            max_length=128,
            return_tensors="pt"
        )

        word_ids = tokenized_inputs.word_ids()
        previous_word_idx = None
        label_ids = []

        for word_idx in word_ids:
            if word_idx is None:
                label_ids.append(-100)
            elif word_idx != previous_word_idx:
                label_ids.append(self.label2id.get(tags[word_idx], 0))
            else:
                label = tags[word_idx]
                if label.startswith("B-"):
                    label = "I-" + label[2:]
                label_ids.append(self.label2id.get(label, 0))
            previous_word_idx = word_idx

        return tokenized_inputs, torch.tensor([label_ids], dtype=torch.long)

    def predict(self, tokens: List[str]) -> List[str]:
        """Runs inference on word tokens using subword-to-word pooling."""
        if not self.model or not self.tokenizer:
            # Fallback to CRF/BiLSTM if transformer model weights are not downloaded
            from .baseline_crf import MultilingualCRFTagger
            crf = MultilingualCRFTagger()
            return crf.predict(tokens)

        self.model.eval()
        inputs = self.tokenizer(
            tokens,
            is_split_into_words=True,
            return_tensors="pt",
            truncation=True
        ).to(self.device)

        with torch.no_grad():
            outputs = self.model(**inputs)
            predictions = torch.argmax(outputs.logits, dim=2)[0].tolist()

        word_ids = inputs.word_ids()
        predicted_tags = []
        seen_words = set()

        for idx, word_idx in enumerate(word_ids):
            if word_idx is not None and word_idx not in seen_words:
                seen_words.add(word_idx)
                tag_id = predictions[idx]
                predicted_tags.append(self.id2label.get(tag_id, "O"))

        # Guarantee output length matches tokens length
        while len(predicted_tags) < len(tokens):
            predicted_tags.append("O")

        return predicted_tags[:len(tokens)]

    def extract_entities(self, text: str, tokens: List[str] = None) -> List[Dict[str, Any]]:
        if tokens is None:
            import re
            tokens = re.findall(r'\w+|[^\w\s]', text)

        tags = self.predict(tokens)
        entities = []
        current = None
        cursor = 0

        for token, tag in zip(tokens, tags):
            t_idx = text.find(token, cursor)
            if t_idx == -1:
                t_idx = cursor
            t_start = t_idx
            t_end = t_start + len(token)
            cursor = t_end

            if tag.startswith("B-"):
                if current:
                    entities.append(current)
                current = {
                    "label": tag[2:],
                    "text": token,
                    "start": t_start,
                    "end": t_end,
                    "tokens": [token]
                }
            elif tag.startswith("I-") and current and tag[2:] == current["label"]:
                current["text"] += " " + token
                current["end"] = t_end
                current["tokens"].append(token)
            else:
                if current:
                    entities.append(current)
                    current = None

        if current:
            entities.append(current)

        return entities

if __name__ == "__main__":
    t_ner = TransformerNER("mBERT")
    print("Transformer NER initialized for mBERT/IndicBERT/XLM-R.")
